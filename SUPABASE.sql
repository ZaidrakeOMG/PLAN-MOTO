create table if not exists public.plan_semanal (
  id bigint generated by default as identity primary key,
  semana integer not null,
  fecha date,
  ingreso numeric(12,2) not null default 0,
  licencia_placas numeric(12,2) not null default 0,
  moto_apartado numeric(12,2) not null default 0,
  quincena_moto text,
  cascos numeric(12,2) not null default 0,
  gasolina numeric(12,2) not null default 0,
  saldo_novia numeric(12,2) not null default 0,
  dar_novia numeric(12,2) not null default 0,
  gym numeric(12,2) not null default 0,
  ahorro numeric(12,2) not null default 0,
  amazon_music numeric(12,2),
  estado text not null default 'Pendiente',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

